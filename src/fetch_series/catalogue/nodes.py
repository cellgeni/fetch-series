# How each INSDC archive's objects are named: the archive's own name for its
# read archive, and the prefix letter its accessions carry.
_ARCHIVE_NAMES = {
    Archive.NCBI: ("SRA", "NCBI SRA", "S"),
    Archive.EBI: ("ENA", "ENA", "E"),
    Archive.DDBJ: ("DRA", "DDBJ DRA", "D"),
}

# The INSDC objects split by archive, with their level and the letters after
# the archive's: SRP, ERS, DRX and so on.
SPLIT: dict[EntityType, tuple[Level, str, str]] = {
    EntityType.STUDY: (Level.DATASET, "study", "RP"),
    EntityType.SAMPLE: (Level.SAMPLE, "sample", "RS"),
    EntityType.EXPERIMENT: (Level.LIBRARY, "experiment", "RX"),
    EntityType.RUN: (Level.RUN, "run", "RR"),
    EntityType.SUBMISSION: (Level.OTHER, "submission", "RA"),
    EntityType.ANALYSIS: (Level.OTHER, "analysis", "RZ"),
}


def object_id(entity: EntityType, archive: Archive) -> str:
    """The node id of one archive's object of one kind: ``run_ebi``."""
    return f"{entity}_{archive}"


def objects(*entities: EntityType, archives: tuple[Archive, ...] = INSDC) -> tuple[str, ...]:
    """Node ids of the given INSDC objects, archive by archive."""
    return tuple(object_id(entity, archive) for archive in archives for entity in entities)


def _object(entity: EntityType, archive: Archive) -> Node:
    level, noun, letters = SPLIT[entity]
    short, database, letter = _ARCHIVE_NAMES[archive]
    return Node(
        object_id(entity, archive),
        f"{short} {noun}",
        level,
        database,
        str(archive),
        entity,
        archive=archive,
        prefix=f"{letter}{letters}",
    )


def _split(entity: EntityType) -> tuple[Node, ...]:
    return tuple(_object(entity, archive) for archive in INSDC)


