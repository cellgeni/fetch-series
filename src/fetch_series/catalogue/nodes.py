_BY_ENTITY: dict[EntityType, str] = {
    node.entity: node.id
    for node in NODES
    if node.entity is not None and node.entity is not EntityType.FILE and node.entity not in SPLIT
}


def node_for(accession: Accession) -> str | None:
    """The node a parsed accession is an instance of.

    An INSDC object lands on its archive's node by its prefix letter, which
    :func:`fetch_series.accession.parse` already reads into ``archive``.
    """
    if accession.entity in SPLIT:
        return object_id(accession.entity, accession.archive)
    return _BY_ENTITY.get(accession.entity)


_FORMAT_OF_KIND = {FileKind.FASTQ: "fastq", FileKind.BAM: "bam", FileKind.CRAM: "cram"}

# SRA Lite objects are named for it wherever NCBI names them: SDL's
# `filetype=sralite` answer is `SRR25056225.lite`, older ones `SRR1552444.sralite`,
# and runinfo's download_path ends `.lite.1`. An SRA object named for its
# accession alone is Normalized: SRA XML calls exactly that file "SRA Normalized"
# (checked on SRR25056225, 2026-10-16).
#
# A directory is not a name. DDBJ files every run it mirrors under
# `dra/sralite/ByExp/litesra/`, and what is there is usually the Normalized
# object: 23 of 29 sampled on 2026-10-19 had its exact size, 3 Lite's.
_LITE = re.compile(r"\.sralite|\.lite(?:\.\d+)?$", re.IGNORECASE)
# NCBI versions the objects it stores: `27865_1_3.cram.1`, `SRR29360814.2`.
_VERSION = re.compile(r"\.\d+$")
_RUN = re.compile(r"[SED]RR\d+")


def is_lite(name: str) -> bool:
    return _LITE.search(name) is not None


def read_format(name: str, *, sra: bool = False) -> str | None:
    """The read-format node a file belongs on, by :func:`files.classify`.

    ``name`` may be a URL. ``sra`` says the archive itself calls the file an SRA
    object (SDL's ``type``). Without it, an SRA object is recognised by its
    name being its run's accession, or by an ``/sra/`` path, since NCBI names
    one for its run alone -- `sra-pub-run-odp/sra/DRR345778/DRR345778`. Lite and
    Normalized are told apart by name. An index or an unrecognised file belongs
    on no read-format node.
    """
    path = name.split("?", 1)[0]
    bare = _VERSION.sub("", path.rsplit("/", 1)[-1])
    kind = classify(bare)
    if kind in _FORMAT_OF_KIND:
        return _FORMAT_OF_KIND[kind]
    if kind is FileKind.INDEX:
        return None
    if is_lite(path):
        return "sra_lite"
    if sra or kind is FileKind.SRA or _RUN.fullmatch(bare) or "/sra/" in path.lower():
        return "sra_normalized"
    return None


