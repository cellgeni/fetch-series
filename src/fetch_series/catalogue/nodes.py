"""The 39 nodes the catalogue links, and the accessions that probe them.

The INSDC objects are split by archive. An ``SRR``, an ``ERR`` and a ``DRR``
share one schema and are mirrored between the three archives, but they are not
reached the same way: ELink's BioProject -> BioSample answers for 99.3% of
NCBI-registered projects and 1.4% of EBI's, and NCBI's Storage Data Locator,
NCBI's runinfo and DDBJ's search each know their own archive's records best.
Merging them into one node hid exactly the split the routing depends on.

BioProject and BioSample stay one node each: all three archives hold the same
record under the same accession, so there is nothing to split. GEO,
ArrayExpress and BioStudies records stay apart from the INSDC ones, because they
are curated records that *point at* INSDC ones rather than mirrors of them --
the distinction :class:`EntityType` already draws.

Read files are nodes by **format**, not by archive: what a pipeline can consume
is a FASTQ, a BAM, a CRAM or an SRA object, whoever lists it. Who made the file
(submitted, or generated by the archive) is a property of the mechanism that
lists it, drawn on the line. Supplementary files and metadata documents are
nodes of their own, per archive, because they are where a record's processed
data and its descriptive metadata actually live.
"""

